#!/usr/bin/env python3
"""Build js/drugs.js from data/drugs_raw.txt (extracted from the study PDF)
and data/hints.txt (one "what it does" hint per drug number).

Usage: python3 tools/build_data.py
"""
import json
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Formulation / packaging suffixes that are not part of the brand name itself.
SUFFIXES = {
    "HFA", "XL", "XR", "CR", "CD", "DS", "ODT", "HCT", "PF", "EC", "SR", "P", "T",
    "R", "N", "AF", "DM", "ES-600", "Respimat", "HandiHaler", "Ellipta", "Consta",
    "Dosepak", "Diskus", "Inhub", "Digihaler", "Nasal", "RediHaler", "Sprinkle",
    "Perles", "Sensimist", "Maintena", "XT",
}

MIN_LEN, MAX_LEN = 3, 13


def brand_word(brand):
    """Return (display, WORD) for a single-token brand, else None."""
    tokens = [t for t in brand.split() if t not in SUFFIXES]
    if len(tokens) != 1:
        return None
    display = tokens[0]
    word = re.sub(r"[^A-Za-z]", "", display).upper()
    if not (MIN_LEN <= len(word) <= MAX_LEN):
        return None
    return display, word


def main():
    hints = {}
    for line in (ROOT / "data/hints.txt").read_text(encoding="utf-8").splitlines():
        if line.strip():
            num, hint = line.split("|", 1)
            hints[int(num)] = hint.strip()

    by_word = defaultdict(list)  # WORD -> [entry,...]
    for line in (ROOT / "data/drugs_raw.txt").read_text(encoding="utf-8").splitlines():
        num, generic, brands = line.split("|", 2)
        num = int(num)
        if num not in hints or brands.strip() in ("—", "-"):
            continue
        seen = set()
        for b in brands.split(","):
            bw = brand_word(b.strip())
            if not bw or bw[1] in seen:
                continue
            seen.add(bw[1])
            by_word[bw[1]].append(
                {"w": bw[1], "brand": bw[0], "generic": generic, "hint": hints[num], "n": num,
                 "plain": bw[0] == b.strip()}
            )

    entries = []
    for word, items in by_word.items():
        # Same word pointing at two different drugs is ambiguous (e.g. Humulin R / N),
        # unless exactly one of them is the plain brand (Diovan beats Diovan HCT).
        if len({i["n"] for i in items}) > 1:
            plain = [i for i in items if i["plain"]]
            if len(plain) != 1:
                print("dropping ambiguous brand:", word)
                continue
            items = plain
        entries.append({k: v for k, v in items[0].items() if k != "plain"})
    entries.sort(key=lambda e: (e["n"], e["w"]))

    out = ROOT / "js/drugs.js"
    out.write_text(
        "// Generated by tools/build_data.py - do not edit by hand.\n"
        "var DRUGS = " + json.dumps(entries, ensure_ascii=False, indent=0) + ";\n",
        encoding="utf-8",
    )
    print(f"{len(entries)} crossword words from {len({e['n'] for e in entries})} drugs")
    lens = defaultdict(int)
    for e in entries:
        lens[len(e["w"])] += 1
    print("length histogram:", dict(sorted(lens.items())))


if __name__ == "__main__":
    main()
